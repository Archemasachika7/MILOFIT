package com.milofit.arena.game

import com.milofit.arena.data.Solid
import com.milofit.arena.data.Tuning
import kotlin.math.abs
import kotlin.math.atan2
import kotlin.math.cos
import kotlin.math.hypot
import kotlin.math.sin

/**
 * Kotlin port of shared/sim-core.js.
 *
 * This is the *same movement rule set the Node server runs*, which is the only
 * reason client-side prediction can work: if the client moved a body with
 * different arithmetic, every snapshot would fight the local guess and the player
 * would rubber-band continuously.
 *
 * Two rules when editing this file:
 *   1. Change shared/sim-core.js first, then mirror it here, then run
 *      `./gradlew :app:test` — SimCoreTest replays a 600-tick trajectory
 *      generated by the JavaScript core and will fail loudly on a divergence.
 *   2. Use Double everywhere. JavaScript numbers are 64-bit floats; Float would
 *      round differently and drift apart over hundreds of ticks.
 *
 * Bullet, explosion and pickup resolution is deliberately absent: on Android the
 * client only predicts its own body, and the server owns everything else.
 */
object SimCore {

    const val EPS = 0.001

    fun clamp(v: Double, lo: Double, hi: Double): Double = if (v < lo) lo else if (v > hi) hi else v

    fun lerp(a: Double, b: Double, t: Double): Double = a + (b - a) * t

    /** Shortest signed difference between two angles, in (-PI, PI]. */
    fun angleDelta(a: Double, b: Double): Double {
        var d = (b - a) % (Math.PI * 2)
        if (d > Math.PI) d -= Math.PI * 2
        if (d < -Math.PI) d += Math.PI * 2
        return d
    }

    fun rectsOverlap(ax: Double, ay: Double, aw: Double, ah: Double, bx: Double, by: Double, bw: Double, bh: Double): Boolean =
        ax < bx + bw && ax + aw > bx && ay < by + bh && ay + ah > by

    /** Is `target` inside the melee cone from `attacker`? */
    fun inMeleeCone(
        attacker: Body,
        target: Body,
        range: Double,
        halfAngleDeg: Double,
    ): Boolean {
        val tx = target.x - attacker.x
        val ty = target.y - attacker.y
        val d = hypot(tx, ty)
        if (d > range + maxOf(target.w, target.h) / 2) return false
        val ang = atan2(ty, tx)
        return abs(angleDelta(attacker.aim, ang)) <= (halfAngleDeg * Math.PI) / 180.0
    }

    /** Which surfaces a move touched. */
    data class Touched(var wall: Boolean = false, var ground: Boolean = false, var ceiling: Boolean = false)

    /**
     * Move a body by (dx, dy), resolving against the map's solids axis by axis.
     *
     * `oneWay` solids are jump-through platforms: ignored on the X axis, and on
     * the Y axis they only block a body that is moving down whose feet were
     * already above the platform before the step.
     *
     * Mutates [body] and returns which surfaces were hit.
     */
    fun moveAndCollide(body: Body, dx: Double, dy: Double, solids: List<Solid>): Touched {
        val touched = Touched()
        val hw = body.w / 2
        val hh = body.h / 2

        if (dx != 0.0) {
            body.x += dx
            var l = body.x - hw
            var r = body.x + hw
            val t = body.y - hh
            val b = body.y + hh
            for (s in solids) {
                if (s.oneWay) continue
                if (r > s.x && l < s.x + s.w && b > s.y && t < s.y + s.h) {
                    body.x = if (dx > 0) s.x - hw - EPS else s.x + s.w + hw + EPS
                    body.vx = 0.0
                    touched.wall = true
                    l = body.x - hw
                    r = body.x + hw
                }
            }
        }

        val prevBottom = body.y + hh
        if (dy != 0.0) {
            body.y += dy
            body.onGround = false
            val l = body.x - hw
            val r = body.x + hw
            val t = body.y - hh
            val b = body.y + hh
            for (s in solids) {
                if (!(r > s.x && l < s.x + s.w && b > s.y && t < s.y + s.h)) continue
                if (s.oneWay) {
                    if (dy <= 0) continue              // moving up: pass through
                    if (prevBottom > s.y + 1) continue // already inside: pass through
                }
                if (dy > 0) {
                    body.y = s.y - hh - EPS
                    body.vy = 0.0
                    body.onGround = true
                    touched.ground = true
                } else {
                    body.y = s.y + s.h + hh + EPS
                    body.vy = 0.0
                    touched.ceiling = true
                }
                break
            }
        } else {
            // A zero vertical step still needs a ground probe (standing still).
            body.onGround = false
            val l = body.x - hw
            val r = body.x + hw
            val b = body.y + hh
            for (s in solids) {
                if (s.oneWay) continue
                val t = body.y - hh
                if (r > s.x && l < s.x + s.w && b > s.y - 1 && t < s.y + s.h && b <= s.y + 1.5) {
                    body.onGround = true
                    break
                }
            }
        }

        return touched
    }

    /**
     * One movement step for a player, identical on server and client.
     *
     * `jump` and `jet` are the same button in the UI — tap on the ground to jump,
     * hold in the air to burn fuel. They stay separate here because Android has a
     * dedicated jetpack button bound to `jet`.
     *
     * Returns whether the jetpack actually fired this step.
     */
    fun stepPlayerMovement(
        p: Body,
        input: PlayerInput,
        dt: Double,
        tuning: Tuning,
        solids: List<Solid>,
    ): Boolean {
        val pl = tuning.player
        val jet = tuning.jetpack
        val gravity = pl.gravity * p.gravityScale

        val wishX = clamp(input.x, -1.0, 1.0)
        if (wishX != 0.0) p.facing = if (wishX > 0) 1 else -1

        val accel = if (p.onGround) 3600.0 else 1900.0
        val targetVx = wishX * (p.runSpeed ?: pl.runSpeed)
        val dq = targetVx - p.vx
        val maxDq = accel * dt
        p.vx += clamp(dq, -maxDq, maxDq)

        if (wishX == 0.0 && p.onGround) {
            p.vx *= Math.pow(0.0009, dt)  // ground friction
        } else if (wishX == 0.0) {
            p.vx *= Math.pow(0.55, dt)    // gentler air drag
        }

        val upHeld = input.jump || input.jet
        var jetting = false

        if (upHeld && p.onGround && !p.jumpHeld) {
            p.vy = pl.jumpVelocity
            p.onGround = false
            p.jumpHeld = true
        } else if (upHeld && !p.onGround && p.jetFuel > 0.0) {
            p.vy += jet.thrust * dt
            if (wishX != 0.0) p.vx += wishX * jet.horizontalThrust * dt
            p.jetFuel = maxOf(0.0, p.jetFuel - jet.drainPerSecond * p.jetDrainScale * dt)
            jetting = true
        }
        if (!upHeld) p.jumpHeld = false

        if (jetting) {
            p.jetIdle = 0.0
        } else {
            p.jetIdle += dt
            // Recharge on the ground immediately, or in the air once the jet has
            // cooled and the player has stopped asking for thrust. Without the
            // `!upHeld` guard, holding the button at zero fuel would let you
            // hover forever.
            val canRecharge = p.onGround ||
                (p.jetIdle > jet.rechargeDelaySeconds && !upHeld)
            if (canRecharge) {
                p.jetFuel = minOf(p.maxJetFuel ?: jet.maxFuel, p.jetFuel + jet.rechargePerSecond * dt)
            }
        }

        p.vy += gravity * dt
        p.vy = clamp(p.vy, jet.maxUpSpeed, pl.maxFallSpeed)

        moveAndCollide(p, p.vx * dt, p.vy * dt, solids)

        // The server trusts the reported aim point but derives the angle itself.
        if (input.aimX.isFinite() && input.aimY.isFinite()) {
            p.aim = atan2(input.aimY - p.y, input.aimX - p.x)
        }

        p.jetting = jetting
        return jetting
    }

    /** Muzzle position along the aim vector, matching the server's `muzzle()`. */
    fun muzzle(p: Body, angle: Double, distance: Double = 18.0): Pair<Double, Double> =
        (p.x + cos(angle) * distance) to (p.y + sin(angle) * distance)

    fun shotsPerSecond(rpm: Double): Double = (if (rpm <= 0.0) 60.0 else rpm) / 60.0

    fun shotInterval(rpm: Double): Double = 1.0 / shotsPerSecond(rpm)
}

/** A body stores its CENTRE in x/y, which makes rendering and camerawork simple. */
class Body(
    var x: Double,
    var y: Double,
    var w: Double,
    var h: Double,
) {
    var vx: Double = 0.0
    var vy: Double = 0.0
    var onGround: Boolean = false
    var jumpHeld: Boolean = false
    var facing: Int = 1
    var aim: Double = 0.0
    var jetFuel: Double = 100.0
    var jetIdle: Double = 1.0
    var jetting: Boolean = false
    var runSpeed: Double? = null
    var maxHealth: Int = 100
    var maxJetFuel: Double? = null
    var jetDrainScale: Double = 1.0
    var gravityScale: Double = 1.0

    val left: Double get() = x - w / 2
    val right: Double get() = x + w / 2
    val top: Double get() = y - h / 2
    val bottom: Double get() = y + h / 2

    fun copyFrom(other: Body) {
        x = other.x
        y = other.y
        vx = other.vx
        vy = other.vy
        onGround = other.onGround
        runSpeed = other.runSpeed
        maxHealth = other.maxHealth
        maxJetFuel = other.maxJetFuel
        jetDrainScale = other.jetDrainScale
        gravityScale = other.gravityScale
    }
}

/**
 * One input frame.
 *
 * `x` is -1..1 (left/right), and `aimX`/`aimY` are a point in world space the
 * player is aiming at — the server derives the angle itself, so a client cannot
 * simply assert a firing angle.
 */
data class PlayerInput(
    val x: Double = 0.0,
    val jump: Boolean = false,
    val jet: Boolean = false,
    val fire: Boolean = false,
    val aimX: Double = 0.0,
    val aimY: Double = 0.0,
    /** Whitelisted one-shot actions: reload | melee | grenade | switch:0 | switch:1 */
    val actions: List<String> = emptyList(),
)
